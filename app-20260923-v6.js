const problemGrid = document.querySelector("#problem-grid");
const articleGrid = document.querySelector("#article-grid");
const dialog = document.querySelector("#article-dialog");
const dialogContent = document.querySelector("#dialog-content");

function renderProblems() {
  problemGrid.innerHTML = problems.map((item) => `
    <button class="problem-card reveal article-link" data-article="${item.id}" type="button">
      <span class="problem-icon" aria-hidden="true">${item.icon}</span>
      <h3>${item.title}</h3><p>${item.text}</p><small>${item.tag} →</small>
    </button>`).join("");
}

function renderArticleCards() {
  articleGrid.innerHTML = articleCards.map((item) => `
    <button class="article-card reveal article-link" data-article="${item.id}" type="button">
      <small>${item.number} · Справочник</small><h3>${item.title}</h3><p>${item.excerpt}</p><b>Читать материал →</b>
    </button>`).join("");
}

function articleHtml(article) {
  return `<p class="article-kicker">${article.category} · Справочник «Высоты»</p>
    <h2>${article.title}</h2><p class="article-summary">${article.summary}</p>
    <h3>Как это может проявляться</h3><ul>${article.symptoms.map(x => `<li>${x}</li>`).join("")}</ul>
    <h3>Возможные причины</h3><ul>${article.causes.map(x => `<li>${x}</li>`).join("")}</ul>
    <h3>Как определяют следующий шаг</h3><p>${article.steps}</p>
    <h3>Что важно знать</h3><p>${article.caution}</p>
    <div class="article-cta"><h3>Не уверены в причине?</h3><p>Пришлите фотографии и коротко опишите, когда появляется проблема. Предварительная оценка не заменяет обследование, но помогает определить следующий шаг.</p><a class="button primary dialog-contact" href="#contact">Перейти к форме</a></div>`;
}

function openArticle(id) {
  const article = articles[id];
  if (!article) return;
  dialogContent.innerHTML = articleHtml(article);
  dialog.showModal();
  dialogContent.querySelector(".dialog-contact").addEventListener("click", () => dialog.close());
}

